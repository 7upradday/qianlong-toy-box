function resolveDynasty(id, name) {
  return id === "m21" || id === "m22" || id === "m30" || name.includes("乾隆") ? "清·乾隆" : "清";
}

function resolveCategory(name, material) {
  if (/香插/.test(name)) return "香插";
  if (/皇帝之宝|之宝$/.test(name)) return "玺印";
  if (/钟|表|风雨/.test(name)) return "钟表仪器";
  if (/核雕/.test(name)) return "雕刻";
  if (material.includes("玉")) return "玉石器";
  if (material.includes("玻璃")) return "玻璃器";
  if (material.includes("漆")) return "漆器";
  if (material.includes("珐琅") && !material.includes("瓷")) return "珐琅器";
  if (/瓷|矾红|洋彩|粉彩/.test(material)) return "陶瓷器";
  if (material === "墨") return "文房用品";
  return "宫廷工艺";
}

function resolveAttribute(name) {
  if (/茶壶|荷花壶|盖碗|茶器|执壶/.test(name)) return "茶器";
  if (/碗|杯/.test(name)) return "饮食器";
  if (/鼻烟壶/.test(name)) return "随身用具";
  if (/水丞/.test(name)) return "文房水器";
  if (/香插/.test(name)) return "香具";
  if (/奔巴|斝/.test(name)) return "礼仪器";
  if (/钟|表|风雨/.test(name)) return "计时与仪器";
  if (/宝/.test(name)) return "皇权凭信";
  if (/墨/.test(name)) return "文房用品";
  if (/核雕/.test(name)) return "微雕清玩";
  if (/瓶|尊|花篮|盘|烛台/.test(name)) return "宫廷陈设";
  return "案头清玩";
}

